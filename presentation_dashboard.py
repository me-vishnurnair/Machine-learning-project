    st.dataframe(pd.DataFrame(rows), hide_index=True, width="stretch")
    st.write("Earlier hours train the models. Middle hours choose the best model and its fraud-score threshold. Later hours measure performance. The boundaries never split the same simulated hour between periods. The full validation and test populations retain their natural class imbalance; headline test results are not calculated on the fraud-enriched sample.")
    st.subheader("4 · Three models and class-imbalance handling")
    for name in ("Logistic Regression", "Random Forest", "XGBoost"):
        st.write(f"**{name}:** {TERM_GLOSSARY[name]}")
    st.write("Rare fraud cases receive extra influence during training through class weights or the boosting model's fraud-class weight. Every fraud row remains in its chronological period; later fraud cases never enter earlier training. No fabricated fraud rows or blanket SMOTE resampling are used.")
    st.write(f"**Selected model: {metadata['selected_model']}.** Candidates are compared on validation data. Their decision thresholds are selected there as well. After selection, each candidate is measured on the same complete later test period. The Model Performance slider is an educational exploration of that fixed test set.")
    st.subheader("5 · Explainability and evaluation")
    st.write("Precision measures useful alerts; recall measures fraud caught; F1 balances them. PR-AUC is the trapezoidal area under the precision–recall curve, while average precision is a separate step-wise summary. ROC-AUC measures ranking. A confusion matrix reports actual false alarms and missed fraud. Accuracy is secondary because legitimate transactions dominate the source.")
    st.write("True SHAP values explain the fitted model globally and for each checked transaction. The feature names are translated into plain English without changing the trained model. SHAP contributions describe model behavior; they do not establish a causal explanation for fraud.")
    with st.expander("Important limitations to explain in a presentation", expanded=True):
        st.write("• PaySim simulates mobile-money fraud rather than real credit-card authorizations. Good simulated results do not establish performance at a real bank.")
        st.write("• Balances after a payment make this a retrospective transaction check. They cannot usually be entered truthfully before a card payment is authorized.")
        st.write("• Amount, sender debit and mismatch formulas work most directly for outgoing transaction types. Deposits and some merchant records have different balance semantics; an unavailable receiver balance is not itself proof of fraud.")
        st.write("• Activity counts may have little variation because many simulated accounts appear only once. They are measured context, not an invented behavioral history.")
        st.write("• Fraud-enriched training changes the observed class rate. The displayed model probability has not been separately calibrated to deployment prevalence.")
