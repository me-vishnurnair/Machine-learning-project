def artifact_directory() -> Path:
    return Path(os.environ.get("PRESENTATION_ARTIFACT_DIR", str(ROOT / "presentation_artifacts"))).resolve()


def file_signature(directory: Path, names: tuple[str, ...]) -> tuple:
    result = []
    for name in names:
        try:
            stat = (directory / name).stat()
            result.append((name, stat.st_size, stat.st_mtime_ns))
        except OSError:
            result.append((name, -1, -1))
    return tuple(result)


@st.cache_resource(show_spinner="Loading the trained presentation model…")
def cached_bundle(directory: str, signature: tuple) -> PresentationBundle:
    return load_bundle(Path(directory))


@st.cache_data(show_spinner="Loading the transaction sample…")
def cached_data(path: str, signature: tuple) -> pd.DataFrame:
    frame = pd.read_parquet(path) if Path(path).suffix == ".parquet" else pd.read_csv(path, float_precision="round_trip")
    if frame.empty:
        raise ValueError("The saved transaction sample is empty.")
    if not set(RAW_FIELDS).issubset(frame.columns) or "isFraud" not in frame:
        raise ValueError("The saved sample is missing required payment details or recorded labels.")
    if not frame["isFraud"].isin([0, 1]).all():
        raise ValueError("The saved sample has invalid recorded fraud labels.")
    return frame


@st.cache_data(show_spinner=False)
def cached_scores(path: str, signature: tuple) -> dict[str, np.ndarray]:
    with np.load(path, allow_pickle=False) as saved:
        arrays = {name: saved[name] for name in saved.files}
    if "labels" not in arrays or arrays["labels"].size == 0:
        raise ValueError("The saved evaluation scores are empty or incomplete.")
    return arrays


