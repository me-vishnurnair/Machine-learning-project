def data_explorer_tab(bundle: PresentationBundle) -> None:
    what_am_i_looking_at("Explore the real saved project sample, with readable column names and filters. It keeps every source fraud row, so fraud appears more often here than in the original source. Charts describe data patterns; a correlation does not prove what caused fraud.")
    heading("Data Explorer", "Know the data before explaining the model.")
    data = _data(bundle)
    columns = st.columns(3)
    classes = columns[0].multiselect("Recorded outcome", ["Legitimate", "Fraud"], default=["Legitimate", "Fraud"], key="presentation_filter_class")
    types = columns[1].multiselect(DISPLAY_NAMES["type"], sorted(data["type"].unique()), default=sorted(data["type"].unique()), format_func=lambda key: TYPE_LABELS.get(key, key.title()), key="presentation_filter_type")
    maximum = columns[2].number_input("Maximum Transaction Amount", min_value=0.0, value=float(data["amount"].max()), step=1000.0, help="Show transactions whose recorded amount is at or below this value. PaySim currency units are not converted to another currency.")
    labels = [value for text, value in (("Legitimate", 0), ("Fraud", 1)) if text in classes]
    filtered = data.loc[data["isFraud"].isin(labels) & data["type"].isin(types) & data["amount"].le(maximum)]
    counts = st.columns(3)
    counts[0].metric("Matching transactions", f"{len(filtered):,}", help="The number of sample transactions left after applying your filters.")
    counts[1].metric("Recorded fraud", f"{int(filtered['isFraud'].sum()):,}", help="Recorded fraud cases among the filtered sample transactions.")
    counts[2].metric("Filtered fraud share", f"{filtered['isFraud'].mean():.2%}" if len(filtered) else "—", help="Fraud cases divided by the filtered transaction count. This is the sample's share, not the natural population fraud rate.")
    if filtered.empty:
        st.info("No transactions match these filters. Choose at least one outcome and transaction type, or increase the amount limit.")
        return
    st.subheader("Transaction preview")
    preview_size = st.select_slider("Rows to preview", options=[10, 25, 50, 100], value=10, key="presentation_preview_size")
    st.dataframe(friendly_frame(filtered.head(preview_size)), hide_index=True, width="stretch")
    with st.expander("What does each displayed column mean?"):
        st.dataframe(pd.DataFrame([{"Column": DISPLAY_NAMES[name], "Plain meaning": FEATURE_GLOSSARY.get(name, "A saved model output or recorded outcome.")} for name in filtered if name in DISPLAY_NAMES]), hide_index=True, width="stretch")
    left, right = st.columns(2)
    with left:
        st.subheader("Transaction types and recorded outcomes")
        chart = go.Figure()
        type_order = sorted(filtered["type"].unique())
        for label, value, color in (("Legitimate", 0, MINT), ("Fraud", 1, ROSE)):
            counts_by_type = filtered.loc[filtered.isFraud.eq(value), "type"].value_counts()
            chart.add_bar(name=label, x=[TYPE_LABELS.get(kind, kind.title()) for kind in type_order], y=[int(counts_by_type.get(kind, 0)) for kind in type_order], marker_color=color)
        chart.update_layout(barmode="group")
        chart.update_yaxes(title="Sample transaction count", type="log")
        st.plotly_chart(style_chart(chart), width="stretch", key="presentation_type_distribution")
        st.caption("Counts use a logarithmic axis. An empty bar means no matching rows for that outcome and type.")
    with right:
        st.subheader("Transaction amounts")
        positive_max = max(float(filtered["amount"].max()), 1.0)
        bins = np.geomspace(0.01, max(positive_max, 0.011), 36)
        centers = np.sqrt(bins[:-1] * bins[1:])
        chart = go.Figure()
        for label, value, color in (("Legitimate", 0, MINT), ("Fraud", 1, ROSE)):
            histogram, _ = np.histogram(np.maximum(filtered.loc[filtered.isFraud.eq(value), "amount"].to_numpy(), 0.01), bins=bins)
            share = histogram / max(int(histogram.sum()), 1)
            chart.add_trace(go.Scatter(x=centers, y=share, name=label, mode="lines", line=dict(color=color, width=2.5)))
        chart.update_xaxes(title=DISPLAY_NAMES["amount"], type="log")
        chart.update_yaxes(title="Share within each recorded class", tickformat=".0%")
        st.plotly_chart(style_chart(chart), width="stretch", key="presentation_amount_distribution")
        st.caption("Amount bins use a logarithmic scale. Each outcome is normalized separately; this compares amount patterns rather than class size.")
    st.subheader("Activity across the day")
    hours = filtered.assign(_hour=filtered["step"] % 24).groupby(["_hour", "isFraud"]).size().unstack(fill_value=0)
    chart = go.Figure()
    for label, value, color in (("Legitimate", 0, MINT), ("Fraud", 1, ROSE)):
        chart.add_trace(go.Scatter(x=hours.index, y=hours.get(value, pd.Series(0, index=hours.index)), name=label, mode="lines+markers", line=dict(color=color)))
    chart.update_xaxes(title=DISPLAY_NAMES["hour_of_day"], dtick=3)
    chart.update_yaxes(title="Sample transaction count", type="log")
    st.plotly_chart(style_chart(chart, 280), width="stretch", key="presentation_hour_distribution")
    st.caption("PaySim has no transaction-duration column. Timing is represented by Hour of Day and earlier sender activity; hour numbers are derived from the simulator's hour counter.")
    with st.expander("Correlation heatmap · numeric features"):
        features = engineer_features(filtered.loc[:, list(RAW_FIELDS)])
        numeric = features.select_dtypes(include="number").copy()
        numeric["isFraud"] = filtered["isFraud"].to_numpy()
        correlation = numeric.corr().rename(index=DISPLAY_NAMES, columns=DISPLAY_NAMES)
        chart = go.Figure(go.Heatmap(z=correlation.to_numpy(), x=list(correlation.columns), y=list(correlation.index), zmin=-1, zmax=1,
                                    colorscale=[[0, LILAC], [.5, "#111A2B"], [1, MINT]], colorbar=dict(title="Correlation"),
                                    hovertemplate="%{y}<br>%{x}: %{z:.2f}<extra></extra>"))
        chart.update_layout(margin=dict(l=10, r=10, t=20, b=180))
        st.plotly_chart(style_chart(chart, 650), width="stretch", key="presentation_correlation")
        st.caption("Values near +1 move together; values near −1 move in opposite directions. Missing cells mean a feature had no variation in this filtered data. Labels are included only for exploration, never as model inputs.")


def model_performance_tab(bundle: PresentationBundle) -> None:
    what_am_i_looking_at("These are measured results on all transactions in the later test period, rather than a balanced demonstration sample. Move the decision threshold to see the real tradeoff between catching fraud and creating false alarms. The slider explores the saved model; it does not retrain or choose a new best model.")
    heading("Model Performance", "Show useful evidence, not just a high accuracy number.")
    record = selected_record(bundle)
    arrays = cached_scores(str(bundle.directory / "evaluation_scores.npz"), file_signature(bundle.directory, ("evaluation_scores.npz",)))
    labels, scores = arrays["labels"], arrays[record["score_array_key"]]
    st.caption(f"Deployed model: {bundle.metadata['selected_model']}. Model and default threshold were chosen using the earlier validation period. Evaluation population: {len(labels):,} later transactions, including {int(labels.sum()):,} recorded fraud cases.")
    threshold = st.slider("Decision threshold · flag when the fraud score reaches this value", min_value=0.0, max_value=1.0,
                          value=default_threshold(bundle), step=0.001, format="%.3f", key="presentation_threshold",
                          help="Lower thresholds usually catch more fraud and raise more false alarms. This slider recomputes predictions from saved scores on the full test period; the trained model is unchanged.")
    st.caption(f"Saved validation-selected threshold: {default_threshold(bundle):.6f}. Current exploratory threshold: {threshold:.6f}.")
    metrics = evaluate_scores(labels, scores, threshold)
    model_metrics(metrics)
    matrix = np.asarray(metrics["confusion_matrix"], dtype=int)
    left, right = st.columns([1, 1.15], gap="large")
    with left:
        st.subheader("Confusion matrix · count every mistake")
        chart = go.Figure(go.Heatmap(z=matrix, x=["Not flagged", "Flagged for review"], y=["Recorded legitimate", "Recorded fraud"],
                                    text=matrix, texttemplate="%{text:,}", colorscale=[[0, "#111A2B"], [1, MINT]], showscale=False,
                                    hovertemplate="%{y}<br>%{x}: %{z:,}<extra></extra>"))
        chart.update_yaxes(autorange="reversed")
        st.plotly_chart(style_chart(chart, 300), width="stretch", key="presentation_confusion_matrix")
        st.write(f"**{matrix[1, 1]:,} fraud cases caught** · **{matrix[1, 0]:,} fraud cases missed**  \n**{matrix[0, 1]:,} false alarms** · **{matrix[0, 0]:,} correct legitimate decisions**")
    with right:
        st.subheader("Precision–recall curve")
        curve = metrics["pr_curve"]
        chart = go.Figure(go.Scatter(x=curve["recall"], y=curve["precision"], mode="lines", line=dict(color=MINT, width=3), name=bundle.metadata["selected_model"]))
        chart.add_hline(y=float(labels.mean()), line_dash="dot", line_color=MUTED)
        chart.update_xaxes(title="Recall · fraction of fraud caught", range=[0, 1], tickformat=".0%")
        chart.update_yaxes(title="Precision · fraction of flags that are fraud", range=[0, 1.03], tickformat=".0%")
        st.plotly_chart(style_chart(chart, 300), width="stretch", key="presentation_pr_curve")
        st.caption("The dotted line is the natural test-period fraud rate. PR-AUC is the actual area under the full precision–recall curve, using trapezoidal integration; it is independent of the current slider threshold. Average precision is a separate, step-wise summary.")
    st.subheader("Three trained models · same later test period")
    rows = []
    for candidate in model_records(bundle.metadata):
        result = candidate["test"]
        rows.append({"Model": candidate["name"] + (" · deployed" if candidate["name"] == bundle.metadata["selected_model"] else ""),
                     "Precision": result["precision"], "Recall": result["recall"], "F1 score": result["f1"],
                     "PR-AUC": result["pr_auc"], "ROC-AUC": result["roc_auc"],
                     "Validation-selected threshold": candidate["threshold"]})
    st.dataframe(pd.DataFrame(rows), hide_index=True, width="stretch", column_config={name: st.column_config.NumberColumn(format="%.8f" if name in ("PR-AUC", "ROC-AUC") else "percent", help="Full later test-period result at this model's own validation-selected threshold.") for name in ("Precision", "Recall", "F1 score", "PR-AUC", "ROC-AUC")})
    st.caption("This table keeps each model's saved validation-selected threshold. Only the deployed model's cards and confusion matrix respond to the slider. Test scores did not select the winning model.")
    with st.expander("Why accuracy is not the headline metric"):
        columns = st.columns(2)
        columns[0].metric("Accuracy at current threshold", f"{metrics['accuracy']:.2%}", help=METRIC_HELP["accuracy"])
        columns[1].metric("Always-legitimate baseline", f"{1 - labels.mean():.2%}", help="Accuracy from predicting every payment as legitimate. This baseline catches zero fraud; it shows why a high accuracy figure can be misleading.")
        st.write("Fraud is rare. A classifier can look accurate by ignoring it. Precision tells us whether review alerts are useful, recall tells us how much fraud is caught, and F1 and PR-AUC summarize the tradeoff.")
    with st.expander("ROC curve · another view of the ranking"):
        curve = metrics["roc_curve"]
        chart = go.Figure(go.Scatter(x=curve["fpr"], y=curve["tpr"], mode="lines", line=dict(color=LILAC, width=3), name=bundle.metadata["selected_model"]))
        chart.add_shape(type="line", x0=0, y0=0, x1=1, y1=1, line=dict(color=MUTED, dash="dot"))
