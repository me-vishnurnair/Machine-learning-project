def _shap_figure(explanation: Any, *, global_plot: bool = False) -> None:
    """Render the genuine SHAP Explanation, keeping all feature labels readable."""
    import matplotlib.pyplot as plt
    import shap
    with plt.rc_context({"figure.facecolor": "#111A2B", "axes.facecolor": "#111A2B", "text.color": TEXT,
                         "axes.labelcolor": TEXT, "xtick.color": TEXT, "ytick.color": TEXT,
                         "axes.edgecolor": MUTED, "font.size": 11}):
        if global_plot:
            shap.plots.beeswarm(explanation, max_display=15, show=False, plot_size=(10, 7))
        else:
            shap.plots.waterfall(explanation, max_display=12, show=False)
        figure = plt.gcf()
        st.pyplot(figure, width="stretch")
        plt.close(figure)


def shap_contribution_table(explanation: Any, bundle: PresentationBundle) -> None:
    """Readable numbers let a presenter verify the waterfall's additive meaning."""
    from presentation_explain import explanation_output_unit
    values = np.asarray(explanation.values, dtype=float).reshape(-1)
    baseline = float(np.asarray(explanation.base_values).reshape(-1)[0])
    st.dataframe(pd.DataFrame({"Feature": list(explanation.feature_names), "SHAP contribution": values})
                 .assign(_magnitude=np.abs(values)).sort_values("_magnitude", ascending=False).drop(columns="_magnitude"),
                 hide_index=True, width="stretch", column_config={"SHAP contribution": st.column_config.NumberColumn(format="%.6f", help="Positive raises the model output; negative lowers it. These are model contributions, not causal evidence.")})
    st.caption(f"Reference value {baseline:.6f} + total contribution {float(values.sum()):+.6f} = model output {baseline + float(values.sum()):.6f} ({explanation_output_unit(bundle)}).")


