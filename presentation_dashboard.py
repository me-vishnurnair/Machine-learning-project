def model_records(metadata: dict) -> list[dict]:
    models = metadata["models"]
    return [{"name": name, **record} for name, record in models.items()] if isinstance(models, dict) else models


def selected_record(bundle: PresentationBundle) -> dict:
    return next(record for record in model_records(bundle.metadata) if record["name"] == bundle.metadata["selected_model"])


def default_threshold(bundle: PresentationBundle) -> float:
    return float(bundle.metadata["threshold"])


def friendly_frame(frame: pd.DataFrame) -> pd.DataFrame:
    """Never leak dataset keys or account identifiers through tables."""
    result = frame.loc[:, [name for name in frame if name in DISPLAY_NAMES]].copy()
    if "type" in result:
        result["type"] = result["type"].map(TYPE_LABELS).fillna("Other")
    if "isFraud" in result:
        result["isFraud"] = result["isFraud"].map({0: "Legitimate", 1: "Fraud"})
    if "prediction" in result:
        result["prediction"] = result["prediction"].map({0: "Not flagged", 1: "Flagged for review"})
    if "account_emptied" in result:
        result["account_emptied"] = result["account_emptied"].map({0: "No", 1: "Yes"})
    return result.rename(columns=DISPLAY_NAMES)


def model_metrics(metrics: dict) -> None:
    """All metric cards have explanations; accuracy stays a secondary measure."""
    columns = st.columns(3)
    for index, (label, key) in enumerate((("Precision", "precision"), ("Recall", "recall"), ("F1 score", "f1"),
                                         ("PR-AUC", "pr_auc"), ("ROC-AUC", "roc_auc"))):
        value = f"{float(metrics[key]):.8f}" if key in ("pr_auc", "roc_auc") else f"{float(metrics[key]):.2%}"
        columns[index % 3].metric(label, value, help=METRIC_HELP[key])


def _data(bundle: PresentationBundle, filename: str = "sample_data.parquet") -> pd.DataFrame:
    return cached_data(str(bundle.directory / filename), file_signature(bundle.directory, (filename,)))


